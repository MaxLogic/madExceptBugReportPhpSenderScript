#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

if [ -f "$REPO_ROOT/.env" ]; then
  set -a
  # shellcheck disable=SC1091
  . "$REPO_ROOT/.env"
  set +a
fi

: "${PUBLIC_URL:?Set PUBLIC_URL in the environment or repo-root .env}"
URL="${PUBLIC_URL%/}/bugreport_mailer.php"

# The customer identifier we're testing for
CUSTOMER="${CUSTOMER_IDENTIFIER:-example-customer}"

ATTACHMENT1="${BUGREPORT_ATTACHMENT:-}"
ATTACHMENT2="${SCREENSHOT_ATTACHMENT:-$SCRIPT_DIR/screen.png}"
TEMP_ATTACHMENT=""

if [ -z "$ATTACHMENT1" ]; then
  TEMP_ATTACHMENT="$(mktemp)"
  printf 'Synthetic test bug report generated by tests/test.sh\n' > "$TEMP_ATTACHMENT"
  ATTACHMENT1="$TEMP_ATTACHMENT"
fi

cleanup() {
  if [ -n "$TEMP_ATTACHMENT" ] && [ -f "$TEMP_ATTACHMENT" ]; then
    rm -f "$TEMP_ATTACHMENT"
  fi
}
trap cleanup EXIT

# --- Pre-flight Checks ---
if [ ! -f "$ATTACHMENT1" ]; then
    echo "Error: Attachment file not found: $ATTACHMENT1"
    exit 1
fi

if [ ! -f "$ATTACHMENT2" ]; then
    echo "Error: Attachment file not found: $ATTACHMENT2"
    exit 1
fi

echo "Preparing to send a test bug report for customer '$CUSTOMER' to $URL..."
echo "----------------------------------------------------------------"

curl -v \
  -F "customerIdentifier=$CUSTOMER" \
  -F "MailSubject=Test Bug Report from Script" \
  -F "MailBody=This is the body of the test bug report. If you see this, it worked! (utf8Test: üÜöÖäÄß-ąĄęĘóÓłŁńŃśŚżŻźŹ)" \
  -F "MailFrom=test-script@paws-server.com" \
  -F "AppName=TestApp" \
  -F "AppVersion=1.0.0" \
  -F "bugreport=@$ATTACHMENT1" \
  -F "screenshot=@$ATTACHMENT2" \
  "$URL"

echo ""
echo "----------------------------------------------------------------"
echo "Done. The request should now be queued first. Run send_queued_reports.php from cron or CLI to deliver it."
